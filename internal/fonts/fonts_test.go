func TestRunAgainstFakeBunny(t *testing.T) {
	var server *httptest.Server
	server = httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch {
		case r.URL.Path == "/css":
			if got := r.URL.RawQuery; got != "family=Open+Sans:400,700" {
				t.Errorf("css query = %s", got)
			}
			io.WriteString(w, "/* latin */\n@font-face {\n  font-family: 'Open Sans';\n  src: url("+server.URL+"/a.woff2) format('woff2'), url('"+server.URL+"/a.woff') format('woff');\n}\n"+
				"@font-face {\n  font-display: block;\n  src: url("+server.URL+"/a.woff2);\n}")
		default:
			io.WriteString(w, "font:"+r.URL.Path)
		}
	}))
	defer server.Close()

	dir := t.TempDir()
	d := Downloader{Client: server.Client(), BaseURL: server.URL, Dir: dir, Log: io.Discard}
	cfg := Config{Families: []Family{{Name: " Open  Sans ", Provider: "bunny", Weights: []int{700, 400, 700}}}}
	if err := d.Run(context.Background(), cfg); err != nil {
		t.Fatal(err)
	}

	css, _ := os.ReadFile(filepath.Join(dir, "fonts.css"))
	want := "/* Generated by `blog fonts download` */\n/* latin */\n@font-face {\n  font-display: swap;\n  font-family: 'Open Sans';\n" +
		"  src: url(\"/fonts/open-sans/open-sans-01.woff2\") format('woff2'), url(\"/fonts/open-sans/open-sans-02.woff\") format('woff');\n}\n" +
		"@font-face {\n  font-display: block;\n  src: url(\"/fonts/open-sans/open-sans-01.woff2\");\n}\n"
	if string(css) != want {
		t.Errorf("fonts.css:\n%s\nwant:\n%s", css, want)
	}
	font, _ := os.ReadFile(filepath.Join(dir, "open-sans", "open-sans-02.woff"))
	if string(font) != "font:/a.woff" {
		t.Errorf("font file = %q", font)
	}

	cfg.Families[0].Provider = "google"
	if err := d.Run(context.Background(), cfg); err == nil || !strings.Contains(err.Error(), "unsupported provider") {
		t.Errorf("err = %v", err)
	}
}

func TestRepoConfig(t *testing.T) {
	cfg, err := LoadConfig("../../fonts.yaml")
	if err != nil {
		t.Fatal(err)
	}
	// Every family in fonts.yaml must have its files committed.
	for _, f := range cfg.Families {
		matches, _ := filepath.Glob(filepath.Join("../../public/fonts", Slug(f.Name), "*.woff2"))
		if len(matches) == 0 {
			t.Errorf("no woff2 files for %s", f.Name)
		}
	}
}
