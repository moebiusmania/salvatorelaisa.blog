// Package fonts downloads the self-hosted font families (fonts.yaml) from
// Bunny Fonts into public/fonts/ and writes the matching fonts.css.
package fonts

import (
	"context"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"

	"go.yaml.in/yaml/v3"
	"golang.org/x/sync/errgroup"
)

// Family is one entry of fonts.yaml.
type Family struct {
	Name     string `yaml:"name"`
	Provider string `yaml:"provider"`
	Weights  []int  `yaml:"weights"`
}

// Config is fonts.yaml.
type Config struct {
	Families []Family `yaml:"families"`
}

// LoadConfig reads fonts.yaml.
func LoadConfig(file string) (Config, error) {
	var cfg Config
	raw, err := os.ReadFile(file)
	if err != nil {
		return cfg, err
	}
	return cfg, yaml.Unmarshal(raw, &cfg)
}

// Downloader fetches fonts; BaseURL is overridable for tests.
type Downloader struct {
	Client  *http.Client
	BaseURL string // https://fonts.bunny.net
	Dir     string // public/fonts
	Log     io.Writer
}

var nonAlnum = regexp.MustCompile(`[^a-z0-9]+`)

// Slug is the folder (and file prefix) used for a family: kebab case.
func Slug(name string) string {
	return strings.Trim(nonAlnum.ReplaceAllString(strings.ToLower(strings.TrimSpace(name)), "-"), "-")
}

// CSSURL is the Bunny Fonts stylesheet for a family, e.g.
// https://fonts.bunny.net/css?family=Lexend:300,400,700,800.
func (d Downloader) CSSURL(f Family) string {
	weights := slices.Clone(f.Weights)
	slices.Sort(weights)
	weights = slices.Compact(weights)
	parts := make([]string, len(weights))
	for i, w := range weights {
		parts[i] = strconv.Itoa(w)
	}
	name := strings.Join(strings.Fields(f.Name), "+")
	return fmt.Sprintf("%s/css?family=%s:%s", d.BaseURL, name, strings.Join(parts, ","))
}

// Run downloads every family and writes fonts.css.
func (d Downloader) Run(ctx context.Context, cfg Config) error {
	if err := os.MkdirAll(d.Dir, 0o755); err != nil {
		return err
	}
	var blocks []string
	for _, f := range cfg.Families {
		if f.Provider != "bunny" {
			return fmt.Errorf("unsupported provider: %s", f.Provider)
		}
		fmt.Fprintf(d.Log, "Downloading %q from %s...\n", f.Name, f.Provider)
		css, err := d.family(ctx, f)
		if err != nil {
			return err
		}
		blocks = append(blocks, css)
	}
	out := filepath.Join(d.Dir, "fonts.css")
	css := "/* Generated by `blog fonts download` */\n" + strings.Join(blocks, "\n\n") + "\n"
	if err := os.WriteFile(out, []byte(css), 0o644); err != nil {
		return err
	}
	fmt.Fprintf(d.Log, "Fonts downloaded to: %s\nCSS generated at: %s\n", d.Dir, out)
	return nil
}

var cssURL = regexp.MustCompile(`url\(([^)]+)\)`)

func cleanURL(raw string) string {
	return strings.Trim(strings.TrimSpace(raw), `'"`)
}

func (d Downloader) family(ctx context.Context, f Family) (string, error) {
	slug := Slug(f.Name)
	dir := filepath.Join(d.Dir, slug)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", err
	}
	css, err := d.get(ctx, d.CSSURL(f))
	if err != nil {
		return "", fmt.Errorf("fetching css for %s: %w", f.Name, err)
	}

	// Unique font URLs, in order of appearance.
	var urls []string
	for _, m := range cssURL.FindAllStringSubmatch(string(css), -1) {
		if u := cleanURL(m[1]); !slices.Contains(urls, u) {
			urls = append(urls, u)
		}
	}

	files := map[string]string{}
	g, gctx := errgroup.WithContext(ctx)
	for i, u := range urls {
		name := fmt.Sprintf("%s-%02d.%s", slug, i+1, extension(u))
		files[u] = name
		g.Go(func() error {
			body, err := d.get(gctx, u)
			if err != nil {
				return err
			}
			return os.WriteFile(filepath.Join(dir, name), body, 0o644)
		})
	}
	if err := g.Wait(); err != nil {
		return "", err
	}
	return RewriteCSS(string(css), slug, files), nil
}

func extension(raw string) string {
	u, err := url.Parse(raw)
	if err != nil {
		return "bin"
	}
	switch ext := strings.TrimPrefix(strings.ToLower(path.Ext(u.Path)), "."); ext {
	case "woff2", "woff", "ttf", "otf":
		return ext
	}
	return "bin"
}

var (
	fontFace     = regexp.MustCompile(`@font-face\s*\{((?s:.*?))\}`)
	fontFaceOpen = regexp.MustCompile(`@font-face\s*\{`)
	fontDisplay  = regexp.MustCompile(`font-display\s*:`)
)

// RewriteCSS points the stylesheet at the local files and adds
// `font-display: swap` to every @font-face that doesn't set it.
func RewriteCSS(css, slug string, files map[string]string) string {
	css = cssURL.ReplaceAllStringFunc(css, func(match string) string {
		name, ok := files[cleanURL(cssURL.FindStringSubmatch(match)[1])]
		if !ok {
			return match
		}
		return fmt.Sprintf(`url("/fonts/%s/%s")`, slug, name)
	})
	return fontFace.ReplaceAllStringFunc(css, func(block string) string {
		if fontDisplay.MatchString(fontFace.FindStringSubmatch(block)[1]) {
			return block
		}
		open := fontFaceOpen.FindString(block)
		return open + "\n  font-display: swap;" + block[len(open):]
	})
}

func (d Downloader) get(ctx context.Context, u string) ([]byte, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, u, nil)
	if err != nil {
		return nil, err
	}
	res, err := d.Client.Do(req)
	if err != nil {
		return nil, err
	}
	defer res.Body.Close()
	if res.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("failed download (%d) for %s", res.StatusCode, u)
	}
	return io.ReadAll(res.Body)
}
